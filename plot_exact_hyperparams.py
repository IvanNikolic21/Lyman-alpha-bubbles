"""Posterior of the bubble-model parameters (x_ion, K) and of the realized ionized fraction, from the exact
pixel likelihood (output of exact_pixel_likelihood.py). numpy / matplotlib only.

WHY THIS WORKS
--------------
Every pool map theta_i was generated by generate_bubble_mocks.py together with its parameters
eta_i = (x_ion_i, K_i): eta_i ~ p(eta) (the mock prior), theta_i ~ p(theta | eta_i). The data depend on eta
only through the map, p(x | theta, eta) = p(x | theta). The pairs (eta_i, theta_i) are therefore samples of
the joint prior p(eta, theta), and weighting them with the same likelihood weights as the pixel posterior,
    w_i = exp L(theta_i) / sum_j exp L(theta_j),   L(theta_i) = sum_g l_g(theta_i)   (saved as `loglik`),
gives samples of the joint posterior p(eta, theta | x). Its eta-marginal is the weighted histogram of the
eta_i. Nothing is recomputed: the per-galaxy log-likelihoods are read from the npz.

QUANTITIES (stored per mock in generate_bubble_mocks.py output)
---------------------------------------------------------------
x_ion     TARGET ionized volume fraction of the Boolean bubble model, prior U(0.1, 0.9). Sets the Poisson
          bubble density lambda = -ln(1 - x_ion) / <V_bubble>. One value for the whole volume (no z-evolution).
k_factor  K / K_fit, prior log-uniform on [0.3, 3]. K is the shape parameter of the exponentially modified
          Gaussian bubble-radius distribution (scipy exponnorm, loc and scale fixed): larger K = longer tail of
          large bubbles. Plotted as k_factor (K_fit = 1.788 is the simulation fit).
realized  fraction of the 43 x 75 sightline points that are inside a bubble in that mock: the ACTUAL ionized
          fraction along our sightlines, which scatters around x_ion (finite volume, Poisson bubble count).

ROW CORRESPONDENCE
------------------
add_mock_observations.py keeps the batch files and row order, and writes theta = 1 - masks with the
sightline axis reversed (masks run from z_end towards the galaxy, theta bin 0 is at the galaxy). With
pool_dir= given, this is checked for every map before anything is plotted.

Usage: python plot_exact_hyperparams.py mocks_dir=<bubble_mocks_run1> [pool_dir=<x dataset>] \\
           [split=val] name=exact_attribution_<model>.npz[:network_pixel_infer.npz] ...
Output: exact_hyperparams.png and a printed table of posterior medians and 68% intervals.
"""
import os
import sys
import glob
import numpy as np
import matplotlib.pyplot as plt

opts, runs = {}, []
for a in sys.argv[1:]:
    k, v = a.split('=', 1)
    if k in ('mocks_dir', 'pool_dir', 'split'):
        opts[k] = os.path.expanduser(v)
    else:
        exact, _, nn = v.partition(':')                      # optional network posterior after ':'
        runs.append((k, os.path.expanduser(exact), os.path.expanduser(nn) if nn else None))
split = opts.get('split', 'val')

# ---- mock parameters, in the sorted batch order used by load_sims / exact_pixel_likelihood.load_pool ----
paths = sorted(glob.glob(os.path.join(opts['mocks_dir'], f'{split}_batch_*.npz')))
if not paths:
    raise FileNotFoundError(f"no {split}_batch_*.npz in {opts['mocks_dir']}")
mocks = [np.load(p) for p in paths]
par = {k: np.concatenate([m[k] for m in mocks]) for k in ('x_ion', 'k_factor', 'K', 'realized')}
n_pool = len(par['x_ion'])

if 'pool_dir' in opts:                                       # row-by-row check theta_i <-> masks_i
    pool_paths = sorted(glob.glob(os.path.join(opts['pool_dir'], f'{split}_batch_*.npz')))
    if [os.path.basename(p) for p in pool_paths] != [os.path.basename(p) for p in paths]:
        raise ValueError('mock and pool directories contain different batch files')
    for pm, pp in zip(paths, pool_paths):
        masks = np.load(pm)['masks']                          # (n, n_gal, n_los), 1 = ionized, far -> near
        theta = np.load(pp)['theta'].reshape(masks.shape)     # 1 = neutral, bin 0 at the galaxy
        if not np.array_equal(theta, 1 - masks[:, :, ::-1]):
            raise ValueError(f'{os.path.basename(pm)}: pool theta does not match the mock masks')
    print(f'[hyper] checked: all {n_pool} pool maps equal 1 - masks (sightline reversed), row by row')


def weights(logL):
    w = np.exp(logL - logL.max())
    return w / w.sum()


def wquantile(v, w, q):
    """Quantiles of a weighted sample (linear interpolation of the weighted CDF)."""
    o = np.argsort(v)
    c = np.cumsum(w[o]) - 0.5 * w[o]
    return np.interp(q, c / c[-1], v[o])


INK, MUTED = '#0b0b0b', '#8a8986'
COLORS = ['#2a78d6', '#1a9e77', '#d81b60']                   # fixed order: model 1, 2, 3
show = [('x_ion', 'target $x_{\\rm ion}$ (bubble model)', np.linspace(0.1, 0.9, 21), False),
        ('realized', 'realized ionized fraction along sightlines', np.linspace(0, 1, 26), False),
        ('k_factor', '$K / K_{\\rm fit}$ (bubble-radius tail)', np.geomspace(0.3, 3, 21), True)]
plt.rcParams.update({'font.size': 10})
fig, axs = plt.subplots(1, 3, figsize=(13, 3.8), layout='constrained')
prior_w = np.full(n_pool, 1.0 / n_pool)
for ax, (key, lab, bins, logx) in zip(axs, show):
    ax.hist(par[key], bins=bins, weights=prior_w, density=True, histtype='stepfilled', color=MUTED,
            alpha=0.3, label='prior (pool)')
    ax.set_xlabel(lab)
    if logx:
        ax.set_xscale('log')
        ax.set_xticks([0.3, 0.5, 1, 2, 3]); ax.set_xticklabels(['0.3', '0.5', '1', '2', '3'])
        ax.minorticks_off()
    for sp in ('top', 'right'):
        ax.spines[sp].set_visible(False)
axs[0].set_ylabel('posterior density')

print(f"{'model':>16s} {'ESS':>6s} " + ' '.join(f'{k:>22s}' for k, *_ in show))
for (name, exact, nn), col in zip(runs, COLORS):
    d = np.load(exact)
    L = d['loglik'].astype(float).sum(axis=1)
    if len(L) != n_pool:
        raise ValueError(f'{exact}: {len(L)} pool maps, mocks have {n_pool}')
    w = weights(L)
    ess = 1 / np.sum(w ** 2)
    row = []
    for ax, (key, lab, bins, logx) in zip(axs, show):
        ax.hist(par[key], bins=bins, weights=w, density=True, histtype='step', lw=1.8, color=col,
                label=f'{name} exact (ESS {ess:.0f})')
        q = wquantile(par[key], w, [0.16, 0.5, 0.84])
        row.append(f'{q[1]:.2f} [{q[0]:.2f}, {q[2]:.2f}]')
        if nn:
            wn = np.load(nn)['weights'].astype(float)
            ax.hist(par[key], bins=bins, weights=wn / wn.sum(), density=True, histtype='step', lw=1.2,
                    ls='--', color=col, label=f'{name} network')
    print(f'{name:>16s} {ess:6.0f} ' + ' '.join(f'{r:>22s}' for r in row))
    if nn:
        wn = np.load(nn)['weights'].astype(float); wn /= wn.sum()
        print(f"{name + ' (NN)':>16s} {1 / np.sum(wn ** 2):6.0f} " + ' '.join(
            f"{'%.2f [%.2f, %.2f]' % tuple(wquantile(par[k], wn, [0.5, 0.16, 0.84])):>22s}" for k, *_ in show))
axs[-1].legend(fontsize=8, frameon=False, loc='upper right')
fig.savefig('exact_hyperparams.png', dpi=170)
print('saved exact_hyperparams.png  (columns: median [16%, 84%])')
